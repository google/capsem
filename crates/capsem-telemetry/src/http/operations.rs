/// Unknown templates share one label; URI values are never admitted.
pub fn normalized_route(path: Option<&str>) -> &'static str {
    path.and_then(|path| ROUTES.binary_search(&path).ok().map(|i| ROUTES[i]))
        .unwrap_or("unmatched")
}
