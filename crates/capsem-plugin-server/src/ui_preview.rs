#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UiPreviewPayload {
    pub generated_by: &'static str,
    pub catalog_id: &'static str,
    pub tool_acceptance: UiToolProgramResult,
    pub examples: Vec<UiPreviewExample>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UiPreviewExample {
    pub name: &'static str,
    pub api: &'static str,
    pub surface: &'static str,
    pub recipe: UiRecipe,
    pub messages: Vec<A2uiServerMessage>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UiRecipe {
    pub component: &'static str,
    pub variant: &'static str,
    pub docs_url: &'static str,
}

impl UiRecipe {
    fn new(component: &'static str, variant: &'static str, docs_url: &'static str) -> Self {
        Self {
            component,
            variant,
            docs_url,
        }
    }
}

impl UiPreviewExample {
    fn new(
        name: &'static str,
        api: &'static str,
        surface: &'static str,
        recipe: UiRecipe,
        document: capsem_plugin_engine::ui::A2uiDocument,
    ) -> Self {
        Self {
            name,
            api,
            surface,
            recipe,
            messages: document.messages,
        }
    }
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ValidateUiRequest {
    pub messages: Vec<A2uiServerMessage>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ValidateUiResponse {
    pub ok: bool,
    pub error: Option<String>,
}
