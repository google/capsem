pub async fn preview_html() -> Html<String> {
    let html = std::fs::read_to_string("ui-preview/dist/index.html").unwrap_or_else(|_| {
        r#"<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>Capsem UI Preview</title>
  </head>
  <body>
    <main style="font-family: system-ui; max-width: 760px; margin: 48px auto;">
      <h1>Capsem UI Preview</h1>
      <p>Build the Svelte preview with <code>npm run ui:build</code>, then refresh.</p>
      <p>The Rust A2UI endpoint is available at <a href="/ui/spec/demo">/ui/spec/demo</a>.</p>
    </main>
  </body>
</html>
"#
        .to_owned()
    });
    Html(html)
}

pub async fn demo() -> Json<UiPreviewPayload> {
    let payload = demo_payload();
    for example in &payload.examples {
        validate_messages(&example.messages)
            .expect("preview examples are generated by typed Rust helpers");
    }
    Json(payload)
}

pub async fn validate(Json(request): Json<ValidateUiRequest>) -> Json<ValidateUiResponse> {
    match validate_messages(&request.messages) {
        Ok(()) => Json(ValidateUiResponse {
            ok: true,
            error: None,
        }),
        Err(error) => Json(ValidateUiResponse {
            ok: false,
            error: Some(error),
        }),
    }
}

